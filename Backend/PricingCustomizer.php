namespace PPADVP\Backend;

// Prevent direct file access.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

use PPADVP\Engine\Base;
use PPADVP\Engine\Traits\AssetLoader;
use Inpsyde\Assets\Asset;
use Inpsyde\Assets\AssetManager;
use Inpsyde\Assets\Script;
use Inpsyde\Assets\Style;

/**
 * Class PricingCustomizer
 */
class PricingCustomizer extends Base {
	use AssetLoader;

	/**
	 * Initialize the class and register hooks.
	 *
	 * @return bool True on success, false on failure.
	 */
	public function initialize(): bool {
		if ( ! parent::initialize() ) {
			return false;
		}

		\add_action( AssetManager::ACTION_SETUP, array( $this, 'enqueue_assets' ) );

		return true;
	}

	/**
	 * Enqueue the custom React application on the pricing page.
	 *
	 * @param AssetManager $asset_manager Asset Manager instance.
	 */
	public function enqueue_assets( AssetManager $asset_manager ): void {
		$screen = \function_exists( 'get_current_screen' ) ? \get_current_screen() : null;

		if ( ! $screen || false === \strpos( (string) $screen->id, 'primeplaced-advanced-password-protection-pricing' ) ) {
			return;
		}

		$config = $this->get_asset_config();

		$style = new Style(
			'ppadvp-pricing-app-css',
			\plugins_url( 'assets/build/primeplaced-advanced-password-protection-pricing.css', \PPADVP_PLUGIN_ABSOLUTE )
		);

		$style->forLocation( Asset::BACKEND )
			->withVersion( $config['version'] );

		$asset_manager->register( $style );

		$script = new Script(
			'ppadvp-pricing-app-js',
			\plugins_url( 'assets/build/primeplaced-advanced-password-protection-pricing.js', \PPADVP_PLUGIN_ABSOLUTE )
		);

		$script->forLocation( Asset::BACKEND )
			->withVersion( $config['version'] )
			->dependencies( ...\array_values( $config['dependencies'] ) );

		$asset_manager->register( $script );
	}

	/**
	 * Retrieves the asset configuration generated by Webpack.
	 *
	 * @return array{dependencies: string[], version: string}
	 */
	private function get_asset_config(): array {
		$path = \plugin_dir_path( \PPADVP_PLUGIN_ABSOLUTE ) . 'assets/build/primeplaced-advanced-password-protection-pricing.asset.php';
		return $this->get_webpack_asset_config( $path, array( 'wp-element', 'wp-components', 'wp-i18n' ) );
	}
}
